import Carbon
import Cocoa

/// Inserts text into whatever text field currently has focus, in any app.
///
/// Clipboard + ⌘V is the one method that works everywhere (Chrome, Electron apps like
/// Slack, native apps, web apps like ChatGPT). The user's clipboard is snapshotted
/// beforehand and restored afterwards, and our temporary entry is marked transient so
/// clipboard managers ignore it.
final class Paster {
    private typealias Snapshot = [[NSPasteboard.PasteboardType: Data]]

    private var pendingRestore: (snapshot: Snapshot, work: DispatchWorkItem)?
    private static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    /// Time the target app gets to read the pasteboard before we put the old contents back.
    /// Electron/Chromium apps read asynchronously, so this errs on the generous side.
    private let restoreDelay: TimeInterval = 0.75

    func paste(_ text: String, restoreClipboard: Bool) {
        let pasteboard = NSPasteboard.general

        // If a previous paste is still waiting to restore, keep *its* snapshot: the current
        // pasteboard only holds our own transient text.
        var snapshot: Snapshot?
        if let pending = pendingRestore {
            pending.work.cancel()
            snapshot = pending.snapshot
            pendingRestore = nil
        } else if restoreClipboard {
            snapshot = Self.snapshot(pasteboard)
        }

        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        if restoreClipboard {
            pasteboard.setData(Data(), forType: Self.transientType)
            pasteboard.setData(Data(), forType: Self.autoGeneratedType)
        }
        let ourChangeCount = pasteboard.changeCount

        sendCommandV()

        guard restoreClipboard, let snapshot else { return }
        let work = DispatchWorkItem { [weak self] in
            self?.pendingRestore = nil
            // Don't clobber something the user copied in the meantime.
            guard pasteboard.changeCount == ourChangeCount else { return }
            Self.restore(snapshot, to: pasteboard)
        }
        pendingRestore = (snapshot, work)
        DispatchQueue.main.asyncAfter(deadline: .now() + restoreDelay, execute: work)
    }

    func copyToClipboard(_ text: String) {
        pendingRestore?.work.cancel()
        pendingRestore = nil
        NSPasteboard.general.clearContents()
        NSPasteboard.general.setString(text, forType: .string)
    }

    private func sendCommandV() {
        // No local-event suppression here: it would swallow real keystrokes (including a ⌥
        // release for the next dictation) for a quarter second after every paste. Setting the
        // flags explicitly is enough to keep physically held modifiers out of the shortcut.
        let source = CGEventSource(stateID: .combinedSessionState)
        let keyCode = Self.keyCodeForV()
        for keyDown in [true, false] {
            guard let event = CGEvent(keyboardEventSource: source, virtualKey: keyCode, keyDown: keyDown) else { continue }
            event.flags = .maskCommand
            event.setIntegerValueField(.eventSourceUserData, value: HotkeyMonitor.syntheticEventMarker)
            event.post(tap: .cgSessionEventTap)
        }
    }

    /// `kTISPropertyUnicodeKeyData`, looked up at runtime because the Command Line Tools SDK
    /// ships without the TextInputSources header that declares it.
    private static let unicodeKeyDataProperty: CFString? = {
        let rtldDefault = UnsafeMutableRawPointer(bitPattern: -2)
        guard let symbol = dlsym(rtldDefault, "kTISPropertyUnicodeKeyData") else { return nil }
        return symbol.assumingMemoryBound(to: CFString.self).pointee
    }()

    /// The key that produces "v" with ⌘ held in the current layout (e.g. differs on Dvorak).
    private static func keyCodeForV() -> CGKeyCode {
        let fallback = CGKeyCode(kVK_ANSI_V)
        guard let property = unicodeKeyDataProperty,
              let source = TISCopyCurrentKeyboardLayoutInputSource()?.takeRetainedValue(),
              let dataPointer = TISGetInputSourceProperty(source, property) else { return fallback }
        let layoutData = Unmanaged<CFData>.fromOpaque(dataPointer).takeUnretainedValue() as Data

        return layoutData.withUnsafeBytes { raw -> CGKeyCode in
            guard let layout = raw.baseAddress?.assumingMemoryBound(to: UCKeyboardLayout.self) else { return fallback }
            for code in 0..<128 {
                var deadKeyState: UInt32 = 0
                var chars = [UniChar](repeating: 0, count: 4)
                var length = 0
                let status = UCKeyTranslate(layout, UInt16(code), UInt16(kUCKeyActionDown),
                                            UInt32((cmdKey >> 8) & 0xFF), UInt32(LMGetKbdType()),
                                            OptionBits(kUCKeyTranslateNoDeadKeysBit), &deadKeyState,
                                            chars.count, &length, &chars)
                if status == noErr, length == 1, chars[0] == UniChar(UnicodeScalar("v").value) {
                    return CGKeyCode(code)
                }
            }
            return fallback
        }
    }

    private static func snapshot(_ pasteboard: NSPasteboard) -> Snapshot {
        (pasteboard.pasteboardItems ?? []).map { item in
            var entry: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) { entry[type] = data }
            }
            return entry
        }
    }

    private static func restore(_ snapshot: Snapshot, to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        guard !snapshot.isEmpty else { return }
        let items = snapshot.map { entry -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in entry { item.setData(data, forType: type) }
            return item
        }
        pasteboard.writeObjects(items)
    }
}
